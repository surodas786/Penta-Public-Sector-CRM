/**
 * Writes one committed migration as a standalone SQL script that a database
 * administrator can review and run by hand (psql) instead of
 * `npm run db:migrate`.
 *
 *   npx tsx scripts/ops/export-migration-sql.ts 0008_section_memberships_and_multi_section_leads
 *
 * The script is the migration file unchanged, wrapped in one transaction with
 * two guards, plus the row drizzle's migrator records for an applied
 * migration (the file's SHA-256 and its journal timestamp). Running it is
 * therefore exactly equivalent to `npm run db:migrate`, and a later
 * `npm run db:migrate` skips it. Output goes to docs/operations/sql/.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const migrations = path.join(root, 'server', 'db', 'migrations');

const tag = process.argv[2];
if (!tag) throw new Error('Usage: export-migration-sql.ts <migration tag, e.g. 0008_section_memberships_and_multi_section_leads>');

const journal = JSON.parse(readFileSync(path.join(migrations, 'meta', '_journal.json'), 'utf8')) as {
  entries: { idx: number; when: number; tag: string }[];
};
const entry = journal.entries.find((item) => item.tag === tag);
if (!entry) throw new Error(`No migration "${tag}" in the journal.`);
const previous = journal.entries.find((item) => item.idx === entry.idx - 1);

const query = readFileSync(path.join(migrations, `${tag}.sql`), 'utf8');
const hash = createHash('sha256').update(query).digest('hex');
const body = query.split('--> statement-breakpoint').join('');

const script = `-- Production upgrade: migration ${tag}
-- Generated by scripts/ops/export-migration-sql.ts from the committed file.
-- Do not edit: regenerate instead. Equivalent to \`npm run db:migrate\`.
--
-- Run as the schema owner (penta_migrator), never the application role:
--   psql "$MIGRATION_DATABASE_URL" -v ON_ERROR_STOP=1 -f ${tag}.production.sql
--
-- Take and verify a backup first (docs/operations/backup-and-restore.md).
-- Everything below is one transaction: any failure, including a pre-flight
-- check, leaves the database exactly as it was.
--
-- migration file sha256: ${hash}
-- journal timestamp:     ${entry.when}

\\set ON_ERROR_STOP on
BEGIN;

-- Guard 1: not already applied.
DO $guard$
BEGIN
  IF EXISTS (SELECT 1 FROM drizzle.__drizzle_migrations WHERE hash = '${hash}') THEN
    RAISE EXCEPTION 'Migration ${tag} is already applied.';
  END IF;
END $guard$;

-- Guard 2: the previous migration is the latest one applied.
DO $guard$
BEGIN
  IF (SELECT max(created_at) FROM drizzle.__drizzle_migrations) IS DISTINCT FROM ${previous ? previous.when : 'NULL'} THEN
    RAISE EXCEPTION 'Expected ${previous?.tag ?? 'no earlier migration'} to be the latest applied migration. Apply migrations in order.';
  END IF;
END $guard$;

${body.trim()}

-- Record it exactly as drizzle's migrator does.
INSERT INTO drizzle.__drizzle_migrations ("hash", "created_at") VALUES ('${hash}', ${entry.when});

COMMIT;
`;

const outDir = path.join(root, 'docs', 'operations', 'sql');
mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, `${tag}.production.sql`);
writeFileSync(outFile, script);
console.log(`Wrote ${path.relative(root, outFile)} (sha256 ${hash}).`);
